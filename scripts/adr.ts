/**
 * Check the architecture decision records under docs/adr/, and write the indexes made from them.
 *
 * Each record lives in the folder of its area, one of AREAS, and is named for its number and
 * title. Its header lines give its status, its date, its tags, and the records it amends or
 * supersedes and is amended or superseded by. The check reports:
 *
 *   misplaced      a record outside an area's folder.
 *   bad-number     a file whose number is not its title's, or a number another record or a
 *                  removed number has.
 *   bad-title      a title that is not "ADR-NNNN: Area: choice".
 *   bad-status     a status that is not proposed, accepted, amended or superseded, or not the one
 *                  the records that amend and supersede it make it.
 *   no-tags        a record with no Tags line, or an empty one.
 *   unknown-tag    a tag the table in docs/adr/tags.md does not list.
 *   unused-tag     a tag the table lists that no record carries.
 *   untagged-area  a record whose title's area word is not among its tags.
 *   broken-link    a header line naming a number that is no record.
 *   one-way        an Amends or Supersedes line the other record's Amended by or Superseded by
 *                  line does not answer, or the other way round.
 *   stale-index    a generated part of docs/adr/README.md, docs/adr/tags.md or docs/SUMMARY.md
 *                  that is not what --write would write.
 *
 * With --write it writes the generated parts instead: the index by area in README.md, the
 * records by tag in tags.md, and the records' entries in SUMMARY.md.
 *
 * Usage: node scripts/adr.ts [--write]
 */

import { readFileSync, writeFileSync } from 'node:fs';
import * as path from 'node:path';

import { type Finding, options, report, runGate } from './lib/cli.ts';
import { tracked, untracked } from './lib/git.ts';
import { ROOT } from './lib/tree.ts';

/** One area: the folder its records live in, the heading the index gives it, and what it holds. */
export interface Area {
    folder: string;
    heading: string;
    holds: string;
}

/** Every area, in the order the index lists them. */
export const AREAS: readonly Area[] = [
    { folder: 'rendering', heading: 'Rendering', holds: 'the realtime renderer: Vulkan, frames, resources, shaders, lighting and textures' },
    { folder: 'text', heading: 'Text', holds: 'fonts, and shaping and drawing text' },
    { folder: 'offline', heading: 'Offline rendering', holds: 'moya, RIB and the offline renderer' },
    { folder: 'ui', heading: 'User interface', holds: '`api/ui`, and the shell a game shares' },
    { folder: 'engine', heading: 'Engine', holds: 'the loop, input, assets, audio, files, the platform and how an app is built' },
    { folder: 'scene', heading: 'Scene', holds: 'grids, the ECS, models, animation, cameras and interchange' },
    { folder: 'editor', heading: 'Editor', holds: 'the editor app' },
    { folder: 'project', heading: 'Project', holds: 'the build, testing, code rules, tooling, documentation, review and releases' },
];

const ADR = 'docs/adr';
const README = `${ADR}/README.md`;
const TAGS = `${ADR}/tags.md`;
const SUMMARY = 'docs/SUMMARY.md';

/** The files in docs/adr/ that are not records. */
const PAGES = new Set(['README.md', 'template.md', 'tags.md']);

/** The lines a generated part of a page sits between. */
export const START = '<!-- generated by scripts/adr.ts -->';
export const END = '<!-- end of generated -->';

/** The SUMMARY.md entry the records' entries are listed under. */
const SUMMARY_PARENT = '- [Architecture Decision Records](adr/README.md)';

const STATUSES = new Set(['proposed', 'accepted', 'amended', 'superseded']);

/** One record, as its file and header lines give it. */
export interface Record {
    file: string;
    folder: string;
    number: number;
    fileNumber: number;
    title: string;
    area: string;
    status: string;
    tags: string[] | null;
    amends: number[];
    amendedBy: number[];
    supersedes: number[];
    supersededBy: number[];
}

/** The numbers a header line names, in the order it names them. */
function numbers(value: string | undefined): number[] {
    return [...(value ?? '').matchAll(/ADR-(\d{4})/g)].map((match) => Number(match[1]));
}

/** A record's fields, from its path relative to the root and its text. */
export function parseRecord(file: string, text: string): Record {
    const lines = text.split(/\r?\n/);
    const header = new Map<string, string>();
    for (const line of lines) {
        const match = line.match(/^\*\*([A-Za-z ]+)\*\*: (.*)$/);
        if (match) {
            header.set(match[1] ?? '', match[2] ?? '');
        }
        if (line.startsWith('## ')) {
            break;
        }
    }
    const titled = (lines[0] ?? '').match(/^# ADR-(\d{4}): (([^:]+): .+)$/);
    const tags = header.get('Tags');
    const relative = file.slice(ADR.length + 1);
    return {
        file,
        folder: relative.includes('/') ? relative.slice(0, relative.indexOf('/')) : '',
        number: titled ? Number(titled[1]) : -1,
        fileNumber: Number(path.basename(file).slice(0, 4)),
        title: titled?.[2] ?? '',
        area: titled?.[3] ?? '',
        status: header.get('Status') ?? '',
        tags: tags === undefined ? null : tags.split(',').map((tag) => tag.trim()).filter((tag) => tag.length > 0),
        amends: numbers(header.get('Amends')),
        amendedBy: numbers(header.get('Amended by')),
        supersedes: numbers(header.get('Supersedes')),
        supersededBy: numbers(header.get('Superseded by')),
    };
}

/** The tag an area word in a title stands for. */
export function tagOf(area: string): string {
    return area.toLowerCase().replace(/\s+/g, '-');
}

/** The tags the table in tags.md lists, each with what it covers. */
export function vocabulary(page: string): Map<string, string> {
    const found = new Map<string, string>();
    for (const match of page.matchAll(/^\| `([^`]+)` \| (.*) \|$/gm)) {
        found.set(match[1] ?? '', match[2] ?? '');
    }
    return found;
}

/** The numbers the table under "Numbers with no record" in README.md lists. */
export function removedNumbers(page: string): Set<number> {
    const section = page.split(/^## /m).find((part) => part.startsWith('Numbers with no record')) ?? '';
    return new Set([...section.matchAll(/^\| (\d{4}) \|/gm)].map((match) => Number(match[1])));
}

/** The records that name a number on one kind of line, by the number they name. */
function namers(records: readonly Record[], pick: (record: Record) => number[]): Map<number, number[]> {
    const found = new Map<number, number[]>();
    for (const record of records) {
        for (const named of pick(record)) {
            found.set(named, [...(found.get(named) ?? []), record.number]);
        }
    }
    return found;
}

/** The status the records that amend and supersede a record make it. */
export function expectedStatus(record: Record, records: readonly Record[]): string {
    if (records.some((other) => other.supersedes.includes(record.number))) {
        return 'superseded';
    }
    if (records.some((other) => other.amends.includes(record.number))) {
        return 'amended';
    }
    return record.status === 'proposed' ? 'proposed' : 'accepted';
}

/** Whether two lists of numbers hold the same numbers. */
function same(first: readonly number[], second: readonly number[]): boolean {
    return [...first].sort().join() === [...second].sort().join();
}

/** What is wrong with one record's place, number, title, status and tags. */
function recordProblems(record: Record, records: readonly Record[], tags: ReadonlyMap<string, string>,
    removed: ReadonlySet<number>): Finding[] {
    const found: Finding[] = [];
    const at = (rule: string, message: string) => found.push({ path: record.file, line: null, rule, message });
    if (!AREAS.some((area) => area.folder === record.folder)) {
        at('misplaced', `a record lives in the folder of its area: ${AREAS.map((area) => area.folder).join(', ')}`);
    }
    if (record.number < 0) {
        at('bad-title', 'the first line is not "# ADR-NNNN: Area: choice"');
    } else if (record.number !== record.fileNumber) {
        at('bad-number', `the file is numbered ${record.fileNumber} and the title ${record.number}`);
    } else if (removed.has(record.number) || records.filter((other) => other.number === record.number).length > 1) {
        at('bad-number', `${record.number} is another record's number, or a removed one`);
    }
    if (!STATUSES.has(record.status)) {
        at('bad-status', `"${record.status}" is not proposed, accepted, amended or superseded`);
    } else if (record.status !== expectedStatus(record, records)) {
        at('bad-status', `the records that amend and supersede it make it ${expectedStatus(record, records)}`);
    }
    if (record.tags === null || record.tags.length === 0) {
        at('no-tags', 'a record has a Tags line naming one tag or more');
    } else {
        for (const tag of record.tags.filter((each) => !tags.has(each))) {
            at('unknown-tag', `${tag} is not in the table in ${TAGS}`);
        }
        if (record.area.length > 0 && !record.tags.includes(tagOf(record.area))) {
            at('untagged-area', `the title's area, ${record.area}, is not among its tags as ${tagOf(record.area)}`);
        }
    }
    return found;
}

/** What is wrong with the links between records. */
function linkProblems(records: readonly Record[]): Finding[] {
    const found: Finding[] = [];
    const known = new Set(records.map((record) => record.number));
    const amenders = namers(records, (record) => record.amends);
    const superseders = namers(records, (record) => record.supersedes);
    for (const record of records) {
        const at = (rule: string, message: string) => found.push({ path: record.file, line: null, rule, message });
        const named = [...record.amends, ...record.amendedBy, ...record.supersedes, ...record.supersededBy];
        for (const missing of named.filter((number) => !known.has(number))) {
            at('broken-link', `ADR-${String(missing).padStart(4, '0')} is no record`);
        }
        if (!same(record.amendedBy, amenders.get(record.number) ?? [])) {
            at('one-way', `its Amended by line names ${record.amendedBy.join(', ') || 'nothing'}, and the records that amend it are ${(amenders.get(record.number) ?? []).join(', ') || 'none'}`);
        }
        if (!same(record.supersededBy, superseders.get(record.number) ?? [])) {
            at('one-way', `its Superseded by line names ${record.supersededBy.join(', ') || 'nothing'}, and the records that supersede it are ${(superseders.get(record.number) ?? []).join(', ') || 'none'}`);
        }
    }
    return found;
}

/** What is wrong with the records, their tags and their links. */
export function problems(records: readonly Record[], tags: ReadonlyMap<string, string>, removed: ReadonlySet<number>): Finding[] {
    const found = records.flatMap((record) => recordProblems(record, records, tags, removed));
    const used = new Set(records.flatMap((record) => record.tags ?? []));
    for (const tag of [...tags.keys()].filter((each) => !used.has(each))) {
        found.push({ path: TAGS, line: null, rule: 'unused-tag', message: `no record carries ${tag}` });
    }
    return [...found, ...linkProblems(records)];
}

/** A record's number as the index writes it. */
function padded(number: number): string {
    return String(number).padStart(4, '0');
}

/** A record's status as the index writes it, naming what amends or supersedes it. */
function statusCell(record: Record, records: readonly Record[]): string {
    const by = (pick: (other: Record) => number[]) =>
        records.filter((other) => pick(other).includes(record.number)).map((other) => other.number).sort((first, second) => first - second)
            .map(padded).join(', ');
    const status = expectedStatus(record, records);
    if (status === 'superseded') {
        return `superseded by ${by((other) => other.supersedes)}`;
    }
    return status === 'amended' ? `amended by ${by((other) => other.amends)}` : status;
}

/** The records in index order: by area, then by number. */
export function ordered(records: readonly Record[]): Record[] {
    const rank = (record: Record) => AREAS.findIndex((area) => area.folder === record.folder);
    return [...records].sort((first, second) => rank(first) - rank(second) || first.number - second.number);
}

/** The index by area that README.md holds, between START and END. */
export function indexPart(records: readonly Record[], removed: ReadonlySet<number>): string {
    const next = Math.max(0, ...records.map((record) => record.number), ...removed) + 1;
    // tables throughout, since a row may run as long as its title and its links make it
    const areas = AREAS.map((area) => `| ${area.heading} | [${area.folder}/](${area.folder}/) | ${area.holds} |`);
    const parts = [`The next record is ADR-${padded(next)}.`, `| Area | Folder | Holds |\n|---|---|---|\n${areas.join('\n')}`];
    for (const area of AREAS) {
        const rows = ordered(records).filter((record) => record.folder === area.folder).map((record) =>
            `| [${padded(record.number)}](${path.posix.relative(ADR, record.file)}) | ${record.title} | ${statusCell(record, records)} | ${(record.tags ?? []).join(', ')} |`);
        parts.push(`### ${area.heading}\n\n| ADR | Decision | Status | Tags |\n|---|---|---|---|\n${rows.join('\n')}`);
    }
    return parts.join('\n\n');
}

/** The records by tag that tags.md holds, between START and END. */
export function tagPart(records: readonly Record[], tags: ReadonlyMap<string, string>): string {
    const parts: string[] = [];
    for (const tag of [...tags.keys()].sort()) {
        const carrying = records.filter((record) => (record.tags ?? []).includes(tag)).sort((first, second) => first.number - second.number);
        const rows = carrying.map((record) => `| [${padded(record.number)}](${path.posix.relative(ADR, record.file)}) | ${record.title} |`);
        parts.push(`### ${tag}\n\n| ADR | Decision |\n|---|---|\n${rows.join('\n')}`);
    }
    return parts.join('\n\n');
}

/** The entries SUMMARY.md lists under the index: the template, the tags, then each record. */
export function summaryEntries(records: readonly Record[]): string[] {
    return [
        '    - [ADR-NNNN: Area: choice in a few plain words](adr/template.md)',
        '    - [Decision record tags](adr/tags.md)',
        ...ordered(records).map((record) => `    - [ADR-${padded(record.number)}: ${record.title}](${record.file.slice('docs/'.length)})`),
    ];
}

/** A page with the text between START and END replaced, or null when it has no such part. */
export function splice(page: string, generated: string): string | null {
    const start = page.indexOf(START);
    const end = page.indexOf(END);
    if (start < 0 || end < start) {
        return null;
    }
    return `${page.slice(0, start + START.length)}\n\n${generated}\n\n${page.slice(end)}`;
}

/** SUMMARY.md with the entries under the index replaced, or null when it has no index entry. */
export function spliceSummary(page: string, entries: readonly string[]): string | null {
    const lines = page.split('\n');
    const parent = lines.indexOf(SUMMARY_PARENT);
    if (parent < 0) {
        return null;
    }
    let end = parent + 1;
    while (end < lines.length && (lines[end] ?? '').startsWith('    - ')) {
        end++;
    }
    return [...lines.slice(0, parent + 1), ...entries, ...lines.slice(end)].join('\n');
}

/** Each record under docs/adr/, read from the tree. */
function readRecords(): Record[] {
    return [...new Set([...tracked(ADR), ...untracked().filter((file) => file.startsWith(`${ADR}/`))])]
        .filter((file) => file.endsWith('.md') && !PAGES.has(path.posix.relative(ADR, file)))
        .map((file) => parseRecord(file, readFileSync(path.join(ROOT, file), 'utf8')));
}

function main(): number {
    const { values } = options('usage: node scripts/adr.ts [--write]', { write: { type: 'boolean' } });
    const records = readRecords();
    const readme = readFileSync(path.join(ROOT, README), 'utf8');
    const tagsPage = readFileSync(path.join(ROOT, TAGS), 'utf8');
    const summary = readFileSync(path.join(ROOT, SUMMARY), 'utf8');
    const tags = vocabulary(tagsPage);
    const removed = removedNumbers(readme);

    const pages: { file: string; was: string; now: string | null }[] = [
        { file: README, was: readme, now: splice(readme, indexPart(records, removed)) },
        { file: TAGS, was: tagsPage, now: splice(tagsPage, tagPart(records, tags)) },
        { file: SUMMARY, was: summary, now: spliceSummary(summary, summaryEntries(records)) },
    ];
    const found = problems(records, tags, removed);
    for (const page of pages) {
        if (page.now === null) {
            found.push({ path: page.file, line: null, rule: 'stale-index', message: 'it has no generated part to write' });
        } else if (values.write) {
            writeFileSync(path.join(ROOT, page.file), page.now);
        } else if (page.now !== page.was) {
            found.push({ path: page.file, line: null, rule: 'stale-index', message: 'run node scripts/adr.ts --write' });
        }
    }
    return report(found, 'breaks the rules for decision records in docs/adr/README.md.');
}

runGate(import.meta.url, main);
